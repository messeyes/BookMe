CREATE TABLE usuario_entity (
                                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                nome varchar(255) NOT NULL,
                                email varchar(255) NOT NULL,
                                senha varchar(255) NOT NULL,
                                cargo varchar(255) NOT NULL,
                                data_cadastro timestamp(6) with time zone NOT NULL,
                                CONSTRAINT usuario_entity_cargo_check
                                    CHECK (cargo IN ('BIBLIOTECARIO', 'ADMINISTRADOR', 'USUARIO'))
);

CREATE TABLE livro_entity (
                              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              isbn bigint NOT NULL UNIQUE,
                              titulo varchar(255) NOT NULL,
                              autor varchar(255) NOT NULL,
                              quant_total integer,
                              quant_disponivel integer
);

CREATE TABLE emprestimo_entity (
                                   id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   id_livro bigint NOT NULL REFERENCES livro_entity (id),
                                   id_usuario bigint NOT NULL REFERENCES usuario_entity (id),
                                   data_emprestimo timestamp(6) with time zone NOT NULL,
                                   data_devol_prevista date NOT NULL,
                                   data_devol_real timestamp(6) with time zone
);

CREATE TABLE multa_entity (
                              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              id_emprestimo bigint NOT NULL UNIQUE REFERENCES emprestimo_entity (id),
                              valor numeric(38,2) NOT NULL,
                              tipo varchar(255) NOT NULL,
                              pago boolean NOT NULL
);

CREATE SEQUENCE reserva_entity_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE reserva_entity (
                                id bigint PRIMARY KEY,
                                id_livro bigint NOT NULL REFERENCES livro_entity (id),
                                id_usuario bigint NOT NULL REFERENCES usuario_entity (id),
                                status varchar(255) NOT NULL,
                                data_reserva timestamp(6) with time zone NOT NULL,
                                ordem_fila integer NOT NULL
);